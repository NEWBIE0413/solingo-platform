def main():
    d = json.load(open("/Users/tmdgus/myworld/solingo-ja-finish/content/ko-topik/placement.json"))
    chs = []
    for unit in d["units"]:
        for les in unit["lessons"]:
            chs.extend(les["challenges"])
    assert len(chs) == len(EX) == 68, f"count mismatch {len(chs)} vs {len(EX)}"
    patched = 0
    for c, (expl, _) in zip(chs, EX):
        correct = next(o["text"] for o in c["options"] if o["correct"])
        meta = dict(c.get("meta") or {})
        meta["explanation"] = expl
        c["meta"] = meta
        patched += 1
    with open("/Users/tmdgus/myworld/solingo-ja-finish/content/ko-topik/placement.json", "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("patched:", patched)

if __name__ == "__main__":
    main()
